/**
 * P1-01 / P2-01: Redirect registry -> deployment configs
 *
 * Reads redirects.config.json and:
 *   1. Merges path-based 301s into vercel.json `redirects` (preserving the existing
 *      www -> non-www host canonicalization rule that must stay FIRST).
 *   2. Writes `nginx-redirects.conf` with matching `location =` blocks so the
 *      Docker/nginx deployment applies the same single-hop 301s.
 *
 * The registry is populated from the GSC 404 export:
 *   Search Console > Indexing > Pages > "Not found (404)" -> the 14 dead URLs.
 * Classify each:
 *   (a) content moved   -> 301 to the new canonical location
 *   (b) typo / legacy   -> 301 to the current slug
 *   (c) perm. removed   -> leave absent from sitemap/internal links; optionally 410
 *
 * Usage:
 *   node scripts/populate-redirects.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.join(__dirname, '..');

const REGISTRY = path.join(ROOT, 'redirects.config.json');
const VERCEL = path.join(ROOT, 'vercel.json');
const NGINX_OUT = path.join(ROOT, 'nginx-redirects.conf');

function loadRegistry() {
  if (!fs.existsSync(REGISTRY)) {
    console.error(`❌ ${REGISTRY} not found. Create it first (see scripts/populate-redirects.mjs header).`);
    process.exit(1);
  }
  const data = JSON.parse(fs.readFileSync(REGISTRY, 'utf8'));
  return Array.isArray(data.redirects) ? data.redirects : [];
}

function normalize(source, destination) {
  const src = source.trim().replace(/\/+$/, '') || '/';
  const dst = destination.trim();
  if (!dst.startsWith('/') && !dst.startsWith('http')) {
    throw new Error(`Invalid destination for ${src}: must be a path or absolute URL`);
  }
  return { source: src, destination: dst };
}

function writeVercelRedirects(redirects) {
  const vercel = JSON.parse(fs.readFileSync(VERCEL, 'utf8'));
  // Keep the existing www -> non-www host redirect FIRST (it must win over path rules).
  const hostRules = (vercel.redirects || []).filter((r) => r?.has && r.has.some((h) => h.type === 'host'));
  const existingPathRules = (vercel.redirects || []).filter((r) => !r?.has);
  const merged = new Map();
  for (const r of [...hostRules, ...existingPathRules, ...redirects]) {
    merged.set(r.source, r);
  }
  vercel.redirects = Array.from(merged.values());
  fs.writeFileSync(VERCEL, JSON.stringify(vercel, null, 2) + '\n', 'utf8');
  return vercel.redirects.length;
}

function writeNginxInclude(redirects) {
  if (redirects.length === 0) {
    fs.writeFileSync(NGINX_OUT, '# No path redirects configured. Populate redirects.config.json then re-run.\n', 'utf8');
    return;
  }
  let out = '# Auto-generated by scripts/populate-redirects.mjs — do not edit by hand.\n';
  out += '# Included from nginx.conf (see `include /etc/nginx/conf.d/redirects.conf;`).\n';
  out += '# Single-hop 301s for P1-01 404 recovery. www canonicalization is handled in nginx.conf itself.\n\n';
  for (const r of redirects) {
    const code = r.permanent === false ? '302' : '301';
    out += `location = ${r.source} { return ${code} ${r.destination}; }\n`;
  }
  fs.writeFileSync(NGINX_OUT, out, 'utf8');
}

function main() {
  const raw = loadRegistry();
  if (raw.length === 0) {
    console.log('ℹ️  redirects.config.json has no entries yet. Skipping vercel.json/nginx output (leaving existing configs untouched).');
    writeNginxInclude([]);
    console.log(`   Wrote empty ${NGINX_OUT}`);
    return;
  }
  const redirects = raw.map((r) => normalize(r.source, r.destination));
  console.log(`🚀 Applying ${redirects.length} redirect(s)...`);
  const total = writeVercelRedirects(redirects);
  writeNginxInclude(redirects);
  console.log(`   ✅ vercel.json now has ${total} redirect rule(s) (host canonicalization kept first).`);
  console.log(`   ✅ Wrote ${NGINX_OUT}`);
  console.log('\nNext steps:');
  console.log('  1. If deployed via Vercel: commit and push; deploy auto-runs.');
  console.log('  2. If deployed via Docker/nginx: ensure nginx.conf includes the generated file, e.g.:');
  console.log('     include /etc/nginx/conf.d/redirects.conf;');
  console.log('  3. Verify: curl -I https://contentanonymity.com<source>  -> expect 301 Location.');
}

main();